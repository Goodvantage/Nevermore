        let themes = NSMenuItem(title: "Theme", action: nil, keyEquivalent: "")
        themes.submenu = ThemeMenuController.shared.makeMenu()
        view.addItem(themes)
        item(view, "Customize Home…", #selector(ConversationWindow.customizeHome(_:)))
        view.addItem(.separator())
        item(view, "Make Text Bigger", #selector(ConversationWindow.largerText(_:)), "+")
        item(view, "Make Text Normal Size", #selector(ConversationWindow.actualTextSize(_:)), "0")
        item(view, "Make Text Smaller", #selector(ConversationWindow.smallerText(_:)), "-")
        view.addItem(.separator())
        item(view, "Enter Full Screen", #selector(NSWindow.toggleFullScreen(_:)), "f", [.command, .control])

        let go = menu("Go")
        item(go, "Home", #selector(ConversationWindow.goHome(_:)), "h", [.command, .shift])
        item(go, "Back", #selector(ConversationWindow.goBack), "[")
        item(go, "Forward", #selector(ConversationWindow.goForward), "]")
        go.addItem(.separator())
        item(go, "Inbox", #selector(ConversationWindow.inbox), "1")
        item(go, "Threads", #selector(ConversationWindow.threads), "2")
        item(go, "Saved Messages", #selector(ConversationWindow.showSavedMessages(_:)), "3")
        item(go, "Reminders", #selector(ConversationWindow.showReminders(_:)), "4")
        item(go, "Scheduled Messages", #selector(ConversationWindow.showScheduledMessages(_:)), "5")
        item(go, "Outbox", #selector(ConversationWindow.outbox), "6")
        go.addItem(.separator())
        item(go, "Next Conversation", #selector(ConversationWindow.nextConversation(_:)), arrowDown, [.command, .option])
        item(go, "Previous Conversation", #selector(ConversationWindow.previousConversation(_:)), arrowUp, [.command, .option])
        item(go, "Next Unread Conversation", #selector(ConversationWindow.nextUnreadConversation(_:)), arrowDown, [.command, .option, .shift])
        go.addItem(.separator())
        item(go, "Next Message", #selector(ConversationWindow.nextMessage(_:)), "]", [.command, .control])
        item(go, "Previous Message", #selector(ConversationWindow.previousMessage(_:)), "[", [.command, .control])
        item(go, "Jump to Latest", #selector(ConversationWindow.jumpToLatest(_:)))
        item(go, "Load Earlier Messages", #selector(ConversationWindow.loadEarlier))
