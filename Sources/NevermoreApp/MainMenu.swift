        item(edit, "Copy", #selector(ComposerClipboard.copyText(_:)), "c", target: ComposerClipboard.shared)
        item(edit, "Paste", #selector(ComposerClipboard.pasteText(_:)), "v", target: ComposerClipboard.shared)
        item(edit, "Paste and Match Style", #selector(ComposerClipboard.pastePlainText(_:)), "v", [.command, .option, .shift], target: ComposerClipboard.shared)
        item(edit, "Delete", #selector(NSText.delete(_:)))
        item(edit, "Select All", #selector(NSText.selectAll(_:)), "a")
        edit.addItem(.separator())
        item(edit, "Copy Transcript", #selector(ConversationWindow.copyTranscript(_:)))
        edit.addItem(.separator())
