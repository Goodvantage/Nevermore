        item(speech, "Start Speaking", #selector(NSTextView.startSpeaking(_:)))
        item(speech, "Stop Speaking", #selector(NSTextView.stopSpeaking(_:)))
        edit.addItem(.separator())
        item(edit, "Emoji & Symbols", #selector(NSApplication.orderFrontCharacterPalette(_:)), " ", [.command, .control])

        let view = menu("View")
        item(view, "Show Sidebar", #selector(NSSplitViewController.toggleSidebar(_:)), "s", [.command, .control])
