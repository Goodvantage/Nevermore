import AppKit

/// The menu bar. Commands with a nil target travel the responder chain, so
/// they act on the focused conversation window and are disabled elsewhere;
/// `ConversationWindow.validateMenuItem` supplies titles and check marks.
///
/// Grouping follows Mail and Messages: File for windows, attachments and
/// printing; Go for navigation and collections; Conversation for the open
/// channel; Message for the message at the caret; Format for the composer.
@MainActor extension AppDelegate {
    func makeMenus() {
        let bar = NSMenu()
        NSApp.mainMenu = bar
        func menu(_ title: String) -> NSMenu {
            let item = NSMenuItem()
            let menu = NSMenu(title: title)
            item.submenu = menu
            bar.addItem(item)
            return menu
        }
        func submenu(_ parent: NSMenu, _ title: String) -> NSMenu {
            let menu = NSMenu(title: title)
            let item = NSMenuItem(title: title, action: nil, keyEquivalent: "")
            item.submenu = menu
            parent.addItem(item)
            return menu
        }
        @discardableResult
        func item(_ menu: NSMenu, _ title: String, _ action: Selector?, _ key: String = "", _ mask: NSEvent.ModifierFlags = .command, target: AnyObject? = nil, tag: Int = 0) -> NSMenuItem {
            let item = NSMenuItem(title: title, action: action, keyEquivalent: key)
            item.keyEquivalentModifierMask = mask
            item.target = target
            item.tag = tag
            menu.addItem(item)
            return item
        }
