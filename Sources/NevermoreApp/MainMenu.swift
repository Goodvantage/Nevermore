        item(conversation, "Schedule Message…", #selector(ConversationWindow.schedule(_:)))
        conversation.addItem(.separator())
        item(conversation, "Open Raven in Browser", #selector(ConversationWindow.openBrowser(_:)))

        let message = menu("Message")
        item(message, "Reply", #selector(ConversationWindow.reply(_:)), "r")
        item(message, "Reply in Thread", #selector(ConversationWindow.openThread(_:)), "t", [.command, .shift])
        item(message, "Open Thread in New Window", #selector(ConversationWindow.openThreadWindow(_:)))
        item(message, "React…", #selector(ConversationWindow.react(_:)))
        message.addItem(.separator())
        item(message, "Edit Message", #selector(ConversationWindow.editMessage(_:)))
        item(message, "Delete Message…", #selector(ConversationWindow.deleteMessage(_:)))
        message.addItem(.separator())
        item(message, "Save for Later", #selector(ConversationWindow.saveForLater(_:)))
        item(message, "Pin / Unpin Message", #selector(ConversationWindow.pin(_:)))
        item(message, "Remind Me…", #selector(ConversationWindow.remind(_:)))
        item(message, "Forward…", #selector(ConversationWindow.forward(_:)))
        item(message, "Copy Message Link", #selector(ConversationWindow.copyMessageLink(_:)))
        message.addItem(.separator())
        item(message, "Who Has Read This?", #selector(ConversationWindow.readers(_:)))
        item(message, "Linked Document…", #selector(ConversationWindow.linkedDocument(_:)))
        item(message, "Open Code Reader…", #selector(ConversationWindow.openCodeReader(_:)))
        item(message, "View / Vote in Poll…", #selector(ConversationWindow.vote(_:)))
        message.addItem(.separator())
        item(message, "Mark Selected Notifications Read", #selector(CollectionWindow.markSelectedRead))

        let format = menu("Format")
        item(format, "Bold", #selector(ComposerView.toggleBoldface(_:)), "b")
        item(format, "Italic", #selector(ComposerView.toggleItalics(_:)), "i")
        item(format, "Underline", #selector(ComposerView.toggleUnderline(_:)), "u")
        item(format, "Strikethrough", #selector(ComposerView.toggleStrikethrough(_:)), "x", [.command, .shift])
        item(format, "Inline Code", #selector(ComposerView.toggleInlineCode(_:)), "k", [.command, .shift])
        item(format, "Code Block", #selector(ComposerView.formatCodeBlock(_:)))
        item(format, "Highlight", #selector(ComposerView.toggleHighlight(_:)))
