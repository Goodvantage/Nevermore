        item(file, "New Channel…", #selector(ConversationWindow.createChannel(_:)))
        file.addItem(.separator())
        item(file, "Open Conversation…", #selector(ConversationWindow.chooseConversation(_:)), "o")
        item(file, "Open in New Window", #selector(ConversationWindow.openConversationWindow(_:)))
        item(file, "Open in New Tab", #selector(ConversationWindow.openConversationTab(_:)))
        file.addItem(.separator())
        item(file, "Attach Files…", #selector(ConversationWindow.attachFiles(_:)), "a", [.command, .shift])
        item(file, "Remove All Attachments", #selector(ConversationWindow.clearAttachments))
        item(file, "Cancel Receiving Files", #selector(ConversationWindow.cancelPromisedFiles(_:)))
        file.addItem(.separator())
        item(file, "Quick Look Attachment", #selector(ConversationWindow.quickLook(_:)), "y")
        item(file, "Save Attachment As…", #selector(ConversationWindow.saveAttachment(_:)))
        file.addItem(.separator())
        item(file, "Close", #selector(NSWindow.performClose(_:)), "w")
