        let conversation = menu("Conversation")
        item(conversation, "Conversation Actions…", #selector(ConversationWindow.showInfo(_:)))
        item(conversation, "Members…", #selector(ConversationWindow.showMembers(_:)))
        item(conversation, "Pinned Messages", #selector(ConversationWindow.showPinnedMessages(_:)))
