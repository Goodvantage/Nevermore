        item(substitutions, "Show Substitutions", #selector(NSTextView.orderFrontSubstitutionsPanel(_:)))
        substitutions.addItem(.separator())
        item(substitutions, "Smart Quotes", #selector(NSTextView.toggleAutomaticQuoteSubstitution(_:)))
        item(substitutions, "Smart Dashes", #selector(NSTextView.toggleAutomaticDashSubstitution(_:)))
        item(substitutions, "Smart Links", #selector(NSTextView.toggleAutomaticLinkDetection(_:)))
