        item(conversation, "Add to Favorites", #selector(ConversationWindow.toggleFavorite(_:)))
        item(conversation, "Mute Conversation", #selector(ConversationWindow.toggleChannelMute(_:)))
        item(conversation, "Mark as Unread", #selector(ConversationWindow.markUnread(_:)), "u", [.command, .shift])
        item(conversation, "Copy Link to Conversation", #selector(ConversationWindow.copyConversationLink(_:)))
        conversation.addItem(.separator())
        item(conversation, "Join Channel", #selector(ConversationWindow.joinChannel(_:)))
        item(conversation, "Add Members…", #selector(ConversationWindow.addChannelMember(_:)))
        item(conversation, "Remove Member…", #selector(ConversationWindow.removeChannelMember(_:)))
        item(conversation, "Archive Conversation…", #selector(ConversationWindow.toggleChannelArchive(_:)))
        item(conversation, "Leave Channel…", #selector(ConversationWindow.leaveChannel(_:)))
        conversation.addItem(.separator())
        item(conversation, "Create Poll…", #selector(ConversationWindow.createPoll(_:)))
